import { defineConfig } from 'vite';
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync } from 'node:fs';

// ШТАМП СБОРКИ.
//
// Файлы приложения ходят между нами по одному: я отдаю их по отдельности,
// они по отдельности кладутся в репозиторий, и рано или поздно один из них
// оказывается не заменён. Ошибка от этого получается тихая и злая — код
// новый, а модуль ядра старый, и поведение не сходится ни с одной из версий.
//
// Поэтому версия здесь не пишется руками. Считается СОДЕРЖИМОЕ каждого
// файла: короткий хеш плюс число строк. Такая версия не может соврать и не
// требует дисциплины — забыть её обновить нельзя, она обновляется сама.
// Число строк дублирует хеш нарочно: его я называю в каждой поставке,
// и глазами оно сверяется быстрее, чем семь шестнадцатеричных знаков.
//
// Версия приложения целиком — хеш от хешей составляющих. Совпал с тем, что
// я назвал, — прод собран ровно из того, что мы наработали. Не совпал —
// список ниже показывает, какой именно файл отстал.
function buildStamp() {
  const files = ['index.html', 'src/app.js', 'public/sw.js']
    .concat(readdirSync('src/core').filter(f => f.endsWith('.js')).sort().map(f => 'src/core/' + f));
  const parts = files.map(name => {
    let text = '';
    try { text = readFileSync(name, 'utf8'); } catch (e) { return { name, hash: 'нет файла', lines: 0 }; }
    return {
      name,
      hash: createHash('sha256').update(text).digest('hex').slice(0, 7),
      // Считаем как wc -l: по переводам строки. Иначе финальный перевод
      // даёт лишнюю единицу, и число не сходится с тем, что названо
      // в поставке, — а ради сверки глазами оно тут и стоит.
      lines: text.split('\n').length - (text.endsWith('\n') ? 1 : 0)
    };
  });
  return {
    id: createHash('sha256').update(parts.map(p => p.hash).join('')).digest('hex').slice(0, 7),
    at: new Date().toISOString(),
    parts
  };
}

// GitHub Pages для проекта отдаёт сайт из подпапки:
//   https://<логин>.github.io/route-planner/
// Поэтому ссылки на ассеты должны быть ОТНОСИТЕЛЬНЫМИ (base './'),
// иначе браузер ищет /assets/... от корня домена и получает 404 —
// ровно это и давало серый экран: HTML грузился, а бандл с картой нет.
export default defineConfig({
  base: './',
  define: {
    // Имя нарочно необщеупотребимое: define подменяет текст, и короткое
    // слово вроде __BUILD__ рискует попасть внутрь чужой строки.
    __DL_BUILD__: JSON.stringify(buildStamp())
  },
  build: {
    // Карта кода: без неё минификатор превращает имена в d, e, t, и ошибка
    // в консоли читается как «d is not defined» — бесполезно для поиска.
    // С картой браузер покажет настоящее имя, файл и строку исходника.
    sourcemap: true,
  },
});
