-- Wialon mileage is no longer a distance source. The browser's validated GPS
-- measurement or an explicit odometer reading remains authoritative.
create or replace function public.trip_fact_km(p_trip uuid)
returns numeric language sql stable security definer set search_path=public as $$
  select round(sum(d)::numeric,1) from (
    select 6371.0088*2*asin(least(1,sqrt(
      power(sin(radians(lat-lag(lat) over w)/2),2)+
      cos(radians(lag(lat) over w))*cos(radians(lat))*power(sin(radians(lng-lag(lng) over w)/2),2)
    ))) d
    from vehicle_positions where trip_id=p_trip window w as(order by ts)
  ) q where d is not null;
$$;

