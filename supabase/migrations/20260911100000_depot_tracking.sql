-- Depot presence, armed trip tracking, and auditable manual odometer values.
-- Raw Wialon mileage is deliberately not used: trip distance comes from GPS
-- geometry or an explicitly entered odometer delta.

alter table public.settings
  add column if not exists depot_radius_m integer not null default 5000,
  add column if not exists depot_exit_margin_m integer not null default 300,
  add column if not exists depot_outside_minutes integer not null default 60,
  add column if not exists company_timezone text not null default 'Europe/Kyiv';

alter table public.vehicle_state
  add column if not exists current_depot_id uuid references public.clients(id) on delete set null,
  add column if not exists depot_state text not null default 'unknown',
  add column if not exists depot_inside_since timestamptz,
  add column if not exists depot_outside_since timestamptz,
  add column if not exists depot_distance_km numeric,
  add column if not exists depot_state_updated_at timestamptz;

alter table public.vehicle_state drop constraint if exists vehicle_state_depot_state_check;
alter table public.vehicle_state add constraint vehicle_state_depot_state_check
  check (depot_state in ('inside','outside_candidate','outside','unknown'));

create table if not exists public.vehicle_depot_events (
  id bigint generated by default as identity primary key,
  vehicle_id uuid not null references public.vehicles(id) on delete cascade,
  depot_id uuid references public.clients(id) on delete set null,
  kind text not null check (kind in ('enter','exit')),
  detected_at timestamptz not null default now(),
  position_ts timestamptz not null,
  lat double precision not null,
  lng double precision not null,
  distance_km numeric,
  trip_id uuid references public.trips(id) on delete set null
);
create index if not exists vehicle_depot_events_vehicle_ts_idx
  on public.vehicle_depot_events(vehicle_id, position_ts desc);

create table if not exists public.trip_tracking_sessions (
  id uuid primary key default gen_random_uuid(),
  trip_id uuid not null unique references public.trips(id) on delete cascade,
  vehicle_id uuid not null references public.vehicles(id) on delete cascade,
  depot_id uuid references public.clients(id) on delete set null,
  state text not null default 'armed' check (state in ('armed','active','finish_candidate','closed','cancelled','reassigned')),
  planned_start_at timestamptz not null,
  capture_from timestamptz not null,
  actual_started_at timestamptz,
  start_source text check (start_source in ('manual','depot_exit')),
  finish_candidate_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists trip_tracking_sessions_vehicle_state_idx
  on public.trip_tracking_sessions(vehicle_id,state,planned_start_at);

create table if not exists public.trip_tracking_points (
  session_id uuid not null references public.trip_tracking_sessions(id) on delete cascade,
  vehicle_id uuid not null references public.vehicles(id) on delete cascade,
  ts timestamptz not null,
  lat double precision not null,
  lng double precision not null,
  speed numeric default 0,
  status text,
  primary key(session_id,ts)
);

create table if not exists public.vehicle_odometer_log (
  id bigint generated by default as identity primary key,
  vehicle_id uuid not null references public.vehicles(id) on delete cascade,
  value_km numeric not null check (value_km >= 0),
  previous_km numeric,
  note text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

