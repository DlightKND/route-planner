create or replace function public.trip_tracking_status_sync()
returns trigger language plpgsql security definer set search_path=public as $$
declare sid uuid; planned timestamptz; depot uuid;
begin
  if new.status='in_progress' and old.status is distinct from 'in_progress' and new.vehicle_id is not null then
    planned:=coalesce(public.trip_planned_start_at(new),new.started_at,now());
    select current_depot_id into depot from vehicle_state where vehicle_id=new.vehicle_id;
    insert into trip_tracking_sessions(trip_id,vehicle_id,depot_id,state,planned_start_at,capture_from,actual_started_at,start_source)
    values(new.id,new.vehicle_id,depot,'active',planned,coalesce(new.started_at,now()),coalesce(new.started_at,now()),'manual')
    on conflict(trip_id) do update set state='active',actual_started_at=coalesce(trip_tracking_sessions.actual_started_at,excluded.actual_started_at),
      start_source=coalesce(trip_tracking_sessions.start_source,excluded.start_source),updated_at=now()
    returning id into sid;
    -- Preserve one trusted anchor immediately before a manual start. Armed
    -- points before it remain in the audit buffer but do not become trip km.
    insert into vehicle_positions(vehicle_id,trip_id,ts,lat,lng,speed,status,moving,mileage)
    select p.vehicle_id,new.id,p.ts,p.lat,p.lng,p.speed,p.status,(p.status='moving'),null
      from trip_tracking_points p where p.session_id=sid and p.ts=(
        select max(x.ts) from trip_tracking_points x where x.session_id=sid and x.ts<=coalesce(new.started_at,now()))
    on conflict(vehicle_id,ts) do nothing;
  elsif new.status in ('finished','done','cancelled') and old.status is distinct from new.status then
    update trip_tracking_sessions set state=case when new.status='cancelled' then 'cancelled' else 'closed' end,
      updated_at=now() where trip_id=new.id and state not in ('closed','cancelled','reassigned');
  end if;
  return new;
end $$;
drop trigger if exists trip_tracking_status_sync on public.trips;
create trigger trip_tracking_status_sync after update of status on public.trips
for each row execute function public.trip_tracking_status_sync();

-- Seed the visible state immediately; subsequent telemetry applies the full
-- pair validation and confirmation timer. An old point outside every depot is
-- deliberately "unknown", not a fabricated departure event.
with nearest as (
  select distinct on (s.vehicle_id) s.vehicle_id,c.id depot_id,
    public.depot_distance_km(s.lat,s.lng,c.lat,c.lng) distance_km
  from vehicle_state s cross join clients c
  where coalesce(c.is_base,false) and c.deleted_at is null
  order by s.vehicle_id,distance_km
)
update vehicle_state s set
  current_depot_id=case when n.distance_km <= coalesce(cfg.depot_radius_m,5000)/1000.0 then n.depot_id else null end,
  depot_state=case when n.distance_km <= coalesce(cfg.depot_radius_m,5000)/1000.0 then 'inside' else 'unknown' end,
  depot_inside_since=case when n.distance_km <= coalesce(cfg.depot_radius_m,5000)/1000.0 then s.ts else null end,
  depot_distance_km=n.distance_km,depot_state_updated_at=s.ts
from nearest n cross join settings cfg
where cfg.id=true and n.vehicle_id=s.vehicle_id;

create or replace function public.push_due(p_kind text default 'trip_today')
returns table(sub_id uuid,endpoint text,p256dh text,auth text,user_id uuid,trip_id uuid,title text,body text)
language sql stable security definer set search_path=public as $$
  with due as (
    select t.*,public.trip_planned_start_at(t) planned_at,coalesce(s.shift_hours,8) shift_h
    from trips t cross join settings s
    where s.id=true and t.deleted_at is null and t.status in ('planned','assigned') and t.started_at is null
  ), recipients as (
    select d.*,d.lead_engineer recipient,'engineer' recipient_kind from due d where d.lead_engineer is not null
    union all
    select d.*,p.id recipient,'manager' recipient_kind from due d join profiles p on p.role in ('admin','logist') and coalesce(p.active,true)
  )
  select ps.id,ps.endpoint,ps.p256dh,ps.auth,r.recipient,r.id,
    case p_kind
      when 'trip_today' then 'Выезд сегодня'
      when 'trip_start_late' then 'Выезд не начат'
      when 'trip_escalated' then 'Выезд просрочен на сутки'
      when 'trip_move' then 'Машина покинула депо'
      else 'Выезд не начат' end,
    coalesce(v.name,r.vehicle_label,'Машина')||' · '||to_char(r.date_from,'DD.MM')||
    case p_kind
      when 'trip_today' then '. Пора начинать выезд.'
      when 'trip_start_late' then '. Машина не покинула депо за рабочий день.'
      when 'trip_escalated' then '. Требуется начать, отменить или переназначить трек.'
      when 'trip_move' then ' движется вне депо, а выезд не начат.'
      else ' до сих пор не начала выезд.' end
  from recipients r join push_subs ps on ps.user_id=r.recipient and ps.fails<5
  left join vehicles v on v.id=r.vehicle_id
  where r.planned_at is not null
    and (
      (p_kind='trip_today' and r.recipient_kind='engineer' and now()>=r.planned_at and now()<r.planned_at+interval '24 hours') or
      (p_kind='trip_start_late' and r.recipient_kind='engineer' and now()>=r.planned_at+make_interval(secs=>round(r.shift_h*3600))) or
      (p_kind='trip_late' and now()>=r.planned_at+make_interval(secs=>round(r.shift_h*3600))) or
      (p_kind='trip_escalated' and now()>=r.planned_at+interval '24 hours') or
      (p_kind='trip_move' and r.recipient_kind='engineer' and r.move_alert_sent)
    )
    and not exists(select 1 from push_log l where l.trip_id=r.id and l.user_id=r.recipient and l.kind=p_kind)

  union all

  select ps.id,ps.endpoint,ps.p256dh,ps.auth,t.lead_engineer,t.id,
    case when p_kind='trip_auto_started' then 'Выезд начат автоматически' else 'Машина вернулась в депо' end,
    coalesce(v.name,t.vehicle_label,'Машина')||case when p_kind='trip_auto_started'
      then ' достаточно долго находилась вне депо. Старт восстановлен по первой точке выхода.'
      else '. Завершить выезд?' end
  from trip_tracking_sessions x join trips t on t.id=x.trip_id
  join push_subs ps on ps.user_id=t.lead_engineer and ps.fails<5
  left join vehicles v on v.id=t.vehicle_id
  where t.lead_engineer is not null and (
      (p_kind='trip_auto_started' and x.start_source='depot_exit' and x.state in ('active','finish_candidate')) or
      (p_kind='trip_finish_candidate' and x.state='finish_candidate')
    ) and not exists(select 1 from push_log l where l.trip_id=t.id and l.user_id=t.lead_engineer and l.kind=p_kind);
$$;

