import {test,expect} from '@playwright/test';
import {installMockBackend,fixtureIDs} from './mock-backend.mjs';
for(const role of ['logist','engineer'])test(role+' sees and opens a presence location without modifying the stay',async({page},info)=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/*',route=>new URL(route.request().url()).origin==='http://127.0.0.1:4173'?route.continue():route.abort());
 await page.clock.setFixedTime(new Date('2026-10-05T17:00:00Z'));
 await page.addInitScript(installMockBackend,{role,theme:info.project.metadata.theme});
 await page.goto('/#/trip/'+fixtureIDs.trip);await expect(page.locator('.view-trip.active')).toBeVisible();
 if(await page.locator('#todayLater').isVisible())await page.locator('#todayLater').click();
 await page.getByRole('tab',{name:'Присутствие',exact:true}).click();
 const preview=page.locator('#tpPresence .presence-location').first();await preview.scrollIntoViewIfNeeded();
 await expect(preview.locator('.leaflet-container')).toBeVisible();await expect(preview.locator('.gps-track-point')).toHaveCount(1);
 await expect(preview).toContainText('49.99000, 36.23000');
 const bounds=await preview.boundingBox();expect(bounds.width).toBeGreaterThan(120);expect(bounds.height).toBeGreaterThan(130);
 if(role==='engineer')await expect(page.locator('#tpPresence input,#tpPresence select,#wbDetect,[data-presence-edit]')).toHaveCount(0);
 await info.attach('presence-location-'+role,{body:await page.screenshot(),contentType:'image/png'});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
 await preview.getByRole('link',{name:'Стоянка 1: открыть на карте',exact:true}).click();
 await expect(page.locator('.view-map.active')).toBeVisible();await expect(page.locator('.leaflet-popup-content')).toContainText('Стоянка 1');
 await expect(page).toHaveURL(new RegExp('/trip/'+fixtureIDs.trip+'/map$'));
 const state=await page.evaluate(()=>window.__visualQA);expect(state.blockedWrites).toEqual([]);expect(state.queryErrors).toEqual([]);expect(state.recoveryWrites).toEqual([]);expect(errors).toEqual([]);
});
